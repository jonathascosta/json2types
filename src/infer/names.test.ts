import { describe, expect, it } from 'vitest';
import { avoidReserved, singular, typeName } from './names';

describe('typeName', () => {
  it.each([
    ['address', 'Address'],
    ['first_name', 'FirstName'],
    ['first name', 'FirstName'],
    ['last-name', 'LastName'],
    ['userId', 'UserId'],
    ['XMLHttpRequest', 'XMLHttpRequest'],
    ['2fa', 'Item2fa'],
    ['', 'Item'],
    ['---', 'Item'],
    ['$ref', 'Ref'],
    ['endereço', 'Endereço'],
    ['café', 'Café'],
    ['x²', 'X'],
    ['½price', 'Price'],
    ['Ⅻ', 'Ⅻ'],
    ['HOME_ADDRESS', 'HomeAddress'],
    ['USER_ID', 'UserID'],
    ['b\u20ddc', 'BC'],
    ['x\u2e2fy', 'XY'],
    ['\u0301abc', 'Abc'],
    ['ßtraße', 'ßtraße'],
    ['𠀀', 'Item'],
    ['𝑥y', 'Y'],
    ['a𠀀b', 'AB'],
    ['version', 'VersionItem'],
    ['date_time_offset', 'DateTimeOffsetItem'],
    ['json_element', 'JsonElementItem'],
    ['pick', 'PickItem'],
    ['jsonPropertyName', 'JsonPropertyNameItem'],
    ['jsonIgnore', 'JsonIgnoreItem'],
    ['json_property_name_attribute', 'JsonPropertyNameAttributeItem'],
    ['obsoleteAttribute', 'ObsoleteAttributeItem'],
    ['orderAttribute', 'OrderAttribute'],
    ['string', 'StringItem'],
    ['date', 'DateItem'],
  ])('%j → %s', (key, name) => {
    expect(typeName(key)).toBe(name);
  });

  it('only produces identifiers valid in C# and TypeScript', () => {
    const keys = [
      'a b',
      'x²',
      '½',
      'a\u0301',
      '١٢٣',
      'über-größe',
      '日本語',
      'emoji😀name',
      'b\u20ddc',
      'x\u2e2fy',
      '𠀀x',
      '𝑥y',
      '\u0301abc',
    ];
    for (const key of keys) {
      const name = typeName(key);
      // C#: a letter or letter number, then letters, Mn, Mc, decimal digits and letter numbers.
      expect(name).toMatch(/^[\p{L}\p{Nl}][\p{L}\p{Mn}\p{Mc}\p{Nd}\p{Nl}]*$/u);
      // ECMAScript: ID_Start, then ID_Continue.
      expect(name).toMatch(/^\p{ID_Start}\p{ID_Continue}*$/u);
      // C# reads identifiers one UTF-16 unit at a time: no surrogate pairs (CS1056).
      expect(name).not.toMatch(/[\u{10000}-\u{10FFFF}]/u);
    }
  });
});

