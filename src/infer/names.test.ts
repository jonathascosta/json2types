describe('avoidReserved', () => {
  it('appends Item to built-in names only', () => {
    expect(avoidReserved('Error')).toBe('ErrorItem');
    expect(avoidReserved('Response')).toBe('ResponseItem');
    expect(avoidReserved('Order')).toBe('Order');
  });
});
